"""Состояние уровня процесса не протекает между тестами (срез-232).

ЧТО БЫЛО. ``services/api_deprecation_recorder`` копит обращения к устаревшим
версиям API в словаре УРОВНЯ МОДУЛЯ — один на процесс. Для боевой работы это
верно: буфер сливают пачкой, чтобы не писать в базу на каждый запрос. Но в
прогоне процесс один на множество тестов, а база у каждого теста СВОЯ. Поэтому
обращение, записанное одним тестом, оставалось в памяти и при первом же вызове
слива попадало в базу СОВСЕМ ДРУГОГО теста.

КАК ПОЙМАЛОСЬ. На параллельном прогоне: проверка уведомлений об устаревших
ручках ждала одно событие, а находила два — второе прилетало от соседа по
процессу. Последовательный прогон это прятал: соседи выстраивались иначе, и
пара «кто записал — кто слил» не складывалась. Параллельный запуск не СОЗДАЛ
дефект, а ПОКАЗАЛ его: тест зависел от порядка.

ЧТО ДЕРЖИТ ЭТОТ СТОРОЖ. Два теста подряд: первый пачкает буфер, второй обязан
увидеть его пустым. Порядок задан именами — pytest выполняет тесты файла сверху
вниз.
"""

from __future__ import annotations

from app.services import api_deprecation_recorder as recorder


def test_1_пачкаем_буфер_процесса() -> None:
    """Первый тест оставляет запись — ровно так, как это делает любой запрос
    к устаревшей ручке в соседнем тесте."""

    recorder.note_deprecated_hit("demo", "/api/v1/files-legacy")
    assert recorder._pending, "запись не легла в буфер — проверка меряет не то"


def test_2_следующий_тест_видит_буфер_пустым() -> None:
    """Иначе слив запишет чужое обращение в базу ЭТОГО теста.

    Доказано поломкой: убери автоматический сброс из корневого conftest — и
    проверка краснеет, а за ней и уведомления об устаревших ручках.
    """

    assert not recorder._pending, (
        "буфер обращений к устаревшим ручкам протёк из предыдущего теста: "
        f"{dict(recorder._pending)}"
    )
