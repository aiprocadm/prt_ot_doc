"""SEC-64, разд. 64.1, строка «Vulnerable Components»: проверка зависимостей не протухла.

ЗАЧЕМ. Инструменты (pip-audit, npm audit, Trivy) и гейты к ним в проекте есть
давно, но жили они ТОЛЬКО внутри CI, а CI выключен вручную с 13.08.2026 по
решению владельца. Получилось худшее сочетание: проверка формально «есть», а на
деле не выполнялась больше месяца — и **молчание читалось как «всё хорошо»**.

Чем это кончилось в первый же запуск после паузы (16.09.2026): 11 известных
уязвимостей на стороне сервера, среди них боевая библиотека шифрования с готовым
исправлением, и восемь блокирующих записей высокой важности на витрине.

ЧТО ДЕЛАЕТ ЭТОТ СТОРОЖ. Он не ищет уязвимости — их ищет
`scripts/ci/run_dependency_audit.py`. Он следит за ДРУГИМ: чтобы проверку вообще
запускали. Если последняя запись в журнале старше срока, обычный прогон тестов
краснеет и говорит, что делать. Так пауза перестаёт быть невидимой.

ПОЧЕМУ ЖУРНАЛ, А НЕ ФАЙЛ-ОТМЕТКА. Дата в журнале стоит рядом с ВЕРДИКТОМ и
списком находок: подделать её, не соврав в тексте рядом, нельзя незаметно.
"""

from __future__ import annotations

import datetime as dt
import re
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parents[1]
LOG_PATH = REPO_ROOT / "docs" / "security" / "DEPENDENCY_AUDIT_LOG.md"

#: Столько дней проверка считается свежей. 30 — ровно та пауза, за которую
#: накопились 19 находок; больше — накопится столько же снова.
FRESH_DAYS = 30

_ENTRY = re.compile(r"^## (\d{4}-\d{2}-\d{2}) — (.+)$", re.MULTILINE)


def _entries() -> list[tuple[dt.date, str]]:
    text = LOG_PATH.read_text(encoding="utf-8")
    return [(dt.date.fromisoformat(day), verdict.strip()) for day, verdict in _ENTRY.findall(text)]


def test_журнал_проверок_существует() -> None:
    assert LOG_PATH.exists(), (
        "нет журнала проверок зависимостей — запустите "
        "`python scripts/ci/run_dependency_audit.py`"
    )


def test_разбор_находит_записи() -> None:
    """Самопроверка разбора: пустой список означал бы зелёный тест ни о чём."""

    assert _entries(), "разбор не нашёл в журнале ни одной записи — он потерял область"


def test_проверка_зависимостей_не_протухла() -> None:
    latest = _entries()[0][0]
    age = (dt.date.today() - latest).days
    assert age <= FRESH_DAYS, (
        f"проверку зависимостей не делали {age} дней (последняя — {latest.isoformat()}). "
        "Запустите `python scripts/ci/run_dependency_audit.py`: инструменты ходят в сеть, "
        "без прогона новые уязвимости не видны, а молчание выглядит как «всё хорошо»."
    )


def test_последняя_проверка_чистая() -> None:
    """Красный вердикт в журнале — это тоже повод не выпускать.

    Записать «есть не принятые находки» и спокойно жить дальше нельзя: либо
    зависимость поднимают, либо находку принимают ЗАПИСЬЮ С ПРИЧИНОЙ И СРОКОМ.
    """

    # Берётся САМАЯ ВЕРХНЯЯ запись: скрипт дописывает новую наверх, значит она
    # и есть последняя. «Любая запись за тот же день» была бы слабее: один
    # чистый прогон рядом с красным прятал бы красный.
    day, verdict = _entries()[0]
    assert "ЧИСТО" in verdict, (
        f"последняя проверка ({day.isoformat()}) нашла не принятые находки: {verdict}. "
        "Поднимите зависимость или примите находку записью в "
        ".github/security-exceptions.yml с причиной и сроком."
    )


@pytest.mark.parametrize(
    ("line", "expected"),
    [
        ("## 2026-09-16 — ЧИСТО", True),
        ("## 2026-09-16 — ЕСТЬ НАХОДКИ", True),
        ("просто текст", False),
    ],
)
def test_разбор_читает_форму_записи(line: str, expected: bool) -> None:
    """Сторож по тексту обязан доказать, ЧТО он считает записью."""

    assert bool(_ENTRY.search(line)) is expected
