"""Юридические тексты партнёра (Доп. №1 разд. 52.2, четвёртый пункт).

Партнёр продаёт платформу под своим именем — значит, и оферту, и политику
обработки ПДн, и текст согласия клиент должен видеть ЕГО. Иначе перебрендирование
косметическое: название чужое, а юридически человек имеет дело непонятно с кем.

Не путать с ``PdnConsent`` (SEC-66): там запись «такой-то субъект дал согласие»,
здесь — сам ТЕКСТ, который ему показали.

Два правила, которые важнее кода:

* **Версионируется, а не правится.** Каждая публикация — новая версия; прежняя
  остаётся. Вопрос «какая редакция действовала в марте» — юридический, и
  ответить на него можно только по неизменной истории. Тот же приём, что у
  ``PdnConsent``.
* **Наследование то же, что у бренда** (свой → партнёра → платформа), и по тем
  же причинам: клиент партнёра, у которого нет своей оферты, должен увидеть
  оферту ПАРТНЁРА, а не платформы.
"""

from __future__ import annotations

from dataclasses import dataclass
from enum import Enum


class LegalDocumentKind(str, Enum):
    """Виды текстов из разд. 52.2. Список закрытый.

    Свободная строка позволила бы завести «оферта2» и «Оферта» как разные виды,
    и вопрос «какая оферта действует» перестал бы иметь однозначный ответ.
    """

    OFFER = "offer"
    PRIVACY = "privacy"
    CONSENT = "consent"


#: Человеческие названия. Держим на сервере: их показывают и экран входа, и
#: кабинет партнёра, а два списка подписей разъехались бы.
LEGAL_KIND_TITLES: dict[LegalDocumentKind, str] = {
    LegalDocumentKind.OFFER: "Публичная оферта",
    LegalDocumentKind.PRIVACY: "Политика обработки персональных данных",
    LegalDocumentKind.CONSENT: "Согласие на обработку персональных данных",
}


@dataclass(frozen=True)
class LegalDocument:
    """Одна редакция одного текста."""

    kind: LegalDocumentKind
    title: str
    body: str
    version: int
    #: Чей текст показан: `self` / `reseller` / `platform`. Нужен интерфейсу,
    #: чтобы честно сказать партнёру «сейчас у клиентов действует текст
    #: платформы», а не оставлять его в уверенности, что опубликован свой.
    source: str


def resolve_legal_document(
    kind: LegalDocumentKind,
    *,
    own: LegalDocument | None,
    reseller: LegalDocument | None,
) -> LegalDocument | None:
    """Какой текст показать этому арендатору.

    В отличие от бренда, поля НЕ смешиваются: половина оферты партнёра и
    половина платформенной — это не документ, а подделка. Побеждает целиком
    ближайшая ступень, у которой текст есть.
    """

    for candidate in (own, reseller):
        if candidate is not None and candidate.body.strip():
            return candidate
    return None
