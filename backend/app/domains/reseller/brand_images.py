"""Картинки бренда: логотип и favicon (Доп. №1 разд. 52.2, первый пункт).

Правила чистые: формат распознаётся по СОДЕРЖИМОМУ, а не по заголовку клиента.
Заголовок — это просто строка в запросе: пришли SVG с подписью ``image/png`` —
и «картинка» исполнилась бы скриптом в браузере каждого, кто открыл страницу
входа (SVG умеет содержать скрипты, а публичная выдача идёт с нашего домена).
По этой же причине SVG не принимается вовсе — только растровые форматы.

Размеры ограничены не ради экономии, а потому что картинка хранится в строке
арендатора и отдаётся на каждый заход на страницу входа: «логотип» в 20 МБ —
это отказ обслуживания собственного экрана входа.
"""

from __future__ import annotations

#: Потолки размеров по виду картинки.
LOGO_MAX_BYTES = 512 * 1024
FAVICON_MAX_BYTES = 128 * 1024

#: Какие форматы принимает каждый вид. У favicon список короче: WebP-иконки
#: не понимает Safari, и «загрузилось, но не показывается» выглядело бы как
#: наша поломка, а не как выбор формата.
LOGO_MEDIA_TYPES = frozenset({"image/png", "image/jpeg", "image/webp"})
FAVICON_MEDIA_TYPES = frozenset({"image/png", "image/x-icon"})


def detect_image_media_type(data: bytes) -> str | None:
    """Определить формат по магическим байтам. Неизвестное — ``None``.

    Никакого «поверим расширению»: расширения в загрузке нет, а заголовку
    клиента верить нельзя (см. модульный докстринг).
    """

    if data.startswith(b"\x89PNG\r\n\x1a\n"):
        return "image/png"
    if data.startswith(b"\xff\xd8\xff"):
        return "image/jpeg"
    if len(data) >= 12 and data[0:4] == b"RIFF" and data[8:12] == b"WEBP":
        return "image/webp"
    if data.startswith(b"\x00\x00\x01\x00"):
        return "image/x-icon"
    return None
