"""Кого затронет приостановка (Доп. №3 разд. 63.1, четвёртая угроза).

ТЗ называет эту угрозу «каскадное отключение КАК ОРУЖИЕ»: приостановка партнёра
либо роняет данные его клиентов, либо блокирует легитимных людей. Обязательные
меры — «safe read-only вместо удаления; АУДИТ КАСКАДА; защита managing tenant».

Режим чтения сделан срезом-3, защита управляющего была и раньше. Не хватало
третьего: **следа**. Приостановка писала в аудит только «статус изменён», а
сколько клиентов при этом ушло в режим чтения — не знал никто. Для меры,
которая должна доказывать «данные не тронуты, задело ровно этих», молчание —
это отсутствие меры.

Здесь — чистые правила: кого считать затронутым и что об этом сказать. Ни базы,
ни HTTP: список арендаторов приходит готовым.
"""

from __future__ import annotations

from dataclasses import dataclass

from app.domains.reseller.hierarchy import RESELLER_KIND, TenantNode


@dataclass(frozen=True)
class CascadeImpact:
    """Последствие смены статуса одного арендатора."""

    #: Затронутые клиенты — те, кто сменит режим работы из-за этого действия.
    affected: tuple[str, ...] = ()
    #: Партнёр ли это. У обычного клиента каскада нет вовсе, и говорить о
    #: «затронутых» бессмысленно — их ноль по определению, а не «пока ноль».
    is_reseller: bool = False

    @property
    def count(self) -> int:
        return len(self.affected)

    @property
    def summary(self) -> str:
        """Строка для аудита и для предупреждения оператору.

        Число вынесено в текст намеренно: запись «cascade: 0» и отсутствие
        записи читаются одинаково глазами, а означают разное.
        """

        if not self.is_reseller:
            return "каскада нет: это не партнёр"
        if not self.affected:
            return "каскад пуст: у партнёра нет клиентов"
        return f"затронуто клиентов: {self.count}"


def plan_suspension_cascade(
    target: TenantNode,
    *,
    children: list[TenantNode],
    activating: bool,
) -> CascadeImpact:
    """Кого затронет смена статуса ``target``.

    ``children`` — арендаторы, чей ``parent_id`` указывает на ``target``.
    Фильтровать их по признаку «сейчас активен» НЕ надо: клиент остаётся
    клиентом партнёра и в приостановленном состоянии, а режим чтения у него
    вычисляется на лету из статуса партнёра (`middleware/reseller_suspension`).
    Считать «затронутыми» только активных значило бы занизить число ровно там,
    где оператор и хочет увидеть полную картину.

    ``activating`` не меняет СОСТАВ затронутых — он меняет смысл: при
    возобновлении те же клиенты выходят из режима чтения. Возвращаем один и тот
    же список, чтобы обе стороны каскада были одинаково прослеживаемы.
    """

    if (target.kind or "").strip().lower() != RESELLER_KIND:
        return CascadeImpact(is_reseller=False)

    affected = tuple(
        sorted(child.slug for child in children if child.parent_id == target.id)
    )
    return CascadeImpact(affected=affected, is_reseller=True)
