"""Суб-биллинг: партнёр тарифицирует своих клиентов (Доп. №1 разд. 52.4).

Срез-2 закрыл партнёру смену тарифов с явной причиной: у него не было потолка,
и он мог выдать клиенту «Всё включено» бесплатно — за счёт владельца платформы.
Здесь появляется потолок, и ограничение снимается.

**Потолок — по НАБОРУ МОДУЛЕЙ, а не по деньгам.** Партнёр не может выдать
клиенту модуль, которого нет у него самого: именно модули владелец платформы
партнёру и продаёт. Деньги, которые партнёр берёт со своего клиента, —
его собственная модель, и платформа в неё не вмешивается (это и есть
«двухуровневый биллинг» из ТЗ).

**Чего здесь НЕТ и почему.** Потолка по квотам (хранилище, число генераций) не
вводим: непонятно, общий это пул на всех клиентов партнёра или предел на
каждого, — а это продуктовое решение владельца, не следствие кода. Квоты
остаются за владельцем платформы, и срез не делает вид, что решил и их.

Правила чистые: на входе — наборы кодов модулей, на выходе — вердикт. Ни базы,
ни HTTP.
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class CeilingVerdict:
    """Помещается ли запрошенный тариф в набор партнёра."""

    allowed: bool
    #: Модули, которых у партнёра нет. Отсортированы — сообщение об отказе
    #: должно быть одинаковым при одинаковой причине, иначе его невозможно
    #: ни проверить тестом, ни узнать в поддержке.
    missing: tuple[str, ...] = ()

    @property
    def reason(self) -> str:
        if self.allowed:
            return ""
        return (
            "нельзя выдать клиенту модули, которых нет у вас: "
            + ", ".join(self.missing)
        )


def check_plan_ceiling(
    *,
    plan_features: set[str],
    reseller_features: set[str],
) -> CeilingVerdict:
    """Проверить тариф клиента против набора партнёра.

    ``reseller_features`` — ДЕЙСТВУЮЩИЙ набор партнёра, включая пробные выдачи:
    пока модуль у партнёра работает, он вправе показать его клиенту. Когда
    пробный срок кончится, следующая смена тарифа клиента уже не пройдёт —
    это честнее, чем запрещать заранее.
    """

    missing = plan_features - reseller_features
    if not missing:
        return CeilingVerdict(allowed=True)
    return CeilingVerdict(allowed=False, missing=tuple(sorted(missing)))


def is_ceiling_applicable(*, actor_sees_everything: bool) -> bool:
    """Нужен ли потолок этому действующему лицу.

    Владельцу платформы — нет: он и есть источник модулей, ограничивать его
    собственным набором бессмысленно (у него в наборе может не быть ничего,
    он ничего себе не выдавал).
    """

    return not actor_sees_everything
