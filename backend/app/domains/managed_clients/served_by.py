"""Кто обслуживает этого арендатора (SEC-63 остаток, Доп. №3 разд. 63.2).

Разд. 63.2 требует, чтобы клиент мог запросить журнал доступа к своим данным.
Срез-2 SEC-63 дал такой журнал — но в кабинете АУТСОРСЕРА: «показать его клиенту
— обязанность аутсорсера по договору». Для клиента в режиме Dedicated это
половина ответа: у него есть собственный арендатор и собственный вход, а следы
работы аутсорсера физически лежат в чужом контуре, и увидеть их он может только
попросив того, за кем и следит.

**Связь ищется по `dedicated_tenant_slug`, а не по родителю.** Родитель нового
арендатора — контур, где нажали кнопку перевода, и если сам аутсорсер является
клиентом реселлера, родителем станет РЕСЕЛЛЕР (правило
`inherited_parent_for_spawned_tenant`), а не аутсорсер. По родителю мы нашли бы
не того, кто работает в данных.
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class ServingOutsourcer:
    """Аутсорсер, ведущий этого клиента, и запись о клиенте у него."""

    #: Арендатор аутсорсера — там лежат записи аудита.
    tenant_id: str
    #: Имя аутсорсера для человека: «кто именно работал в моих данных».
    tenant_name: str
    #: Идентификатор записи клиента у аутсорсера — по нему фильтруется журнал.
    managed_client_id: str


@dataclass(frozen=True)
class ClientAccessView:
    """Что показать клиенту.

    `served_by = None` — обычное состояние, а не ошибка: арендатора никто не
    обслуживает. Отвечать отказом было бы неверно — вопрос «кто работал в моих
    данных» законен и тогда, когда ответ «никто».
    """

    served_by: ServingOutsourcer | None

    @property
    def is_served(self) -> bool:
        return self.served_by is not None

    @property
    def summary(self) -> str:
        if self.served_by is None:
            return "Вашими данными не работает обслуживающая компания"
        return f"Ваши данные ведёт: {self.served_by.tenant_name}"
