"""BIZ-49 (разд. 49.3): личность специалиста аутсорсера ВНУТРИ контура клиента.

ЧТО БЫЛО. У Dedicated-клиента данные лежат в ДРУГОМ арендаторе. Срез-126
научил платформу ЧИТАТЬ такой контур для сводки портфеля, и там же честно
записан остаток: «интерактивная работа человека внутри контура клиента (вход,
запись)» не сделана, потому что **строки ``User`` живут в схеме арендатора** —
у специалиста аутсорсера в контуре клиента просто нет личности.

Это не мелочь реализации. Боевая проверка прав (``core/security.rbac``) на
КАЖДОМ запросе достаёт пользователя по ``sub`` из схемы текущего арендатора и
сверяет ``user.tenant_id`` с арендатором токена. Значит «пустить специалиста в
контур клиента» = «дать ему там настоящую личность», а не выдать особый токен и
ослабить проверку. Ослаблять её ради одной фичи нельзя: она держит изоляцию
всего продукта.

РЕШЕНИЯ, КОТОРЫЕ ВАЖНЕЕ КОДА.

**1. Личность заводит ПЛАТФОРМА по гранту, а не человек руками.** Заведённую
руками забывают отозвать — и она остаётся дверью в контур клиента после того,
как договор кончился. Здесь личность — следствие гранта и согласия: нет
основания, нет личности.

**2. Адрес личности НЕ МОЖЕТ существовать в природе.** Домен ``.invalid``
зарезервирован RFC 2606 навсегда и не делегируется никому. Отсюда сразу три
следствия: письмо такой личности физически не уйдёт; настоящий сотрудник
клиента не сможет занять этот адрес; а найти личность можно ВЫЧИСЛЕНИЕМ адреса,
без второй таблицы-указателя, которая рассинхронизируется с жизнью.

**3. У личности нет пароля.** В поле хэша стоит метка, которую не выдаёт ни
один хэшер. Будь у личности пароль — у неё появился бы ВТОРОЙ вход, который
переживёт и отзыв гранта, и отзыв согласия, и о котором аутсорсер не узнает.
Вход по паролю для неё запрещён ЯВНОЙ проверкой, а не тем, что «хэш всё равно
не сойдётся»: случайная защита исчезает при первой же смене хэшера.

**4. Административные роли НЕ делегируются.** В чужом контуре специалист —
специалист. Владение контуром (пользователи, безопасность, оплата) — дело
клиента, и аутсорсер не должен получать его вместе с правом вести охрану труда.
Профессиональная роль зеркалится как есть, любая другая опускается до
``ot_specialist``.

**5. Гашение немедленное.** Выход из контекста, отзыв согласия, снятие гранта —
личность гасится (``is_active = false``). Это работает сразу и не ждёт
истечения токена, потому что проверка прав перечитывает пользователя на КАЖДОМ
запросе: токен ещё жив, доступа уже нет.

**6. Личность ВИДНА клиенту.** Имя прямо называет, чей это специалист. Клиент,
открыв список пользователей своего контура, обязан понимать, кто эти люди —
безымянная служебная учётка выглядела бы как взлом.

ГРАНИЦА НАЗВАНА. Здесь только правила: как называется личность, какую роль она
получает, чего у неё не бывает. Заведение и гашение строк — в
``services/managed_client_identity.py``; право на вход — в ``delegation.py``.
"""

from __future__ import annotations

import re

from app.models.tenant_billing import RoleEnum

__all__ = [
    "DELEGATED_CLIENT_CLAIM",
    "DELEGATED_EMAIL_DOMAIN_SUFFIX",
    "DELEGATED_FROM_CLAIM",
    "DELEGATED_PASSWORD_MARK",
    "DEFAULT_DELEGATED_ROLE",
    "DELEGATABLE_ROLES",
    "delegated_display_name",
    "delegated_email",
    "delegated_role",
    "is_delegated_email",
    "is_delegated_password",
]

#: Метки в токене контура. Токен обязан САМ говорить, что он делегированный:
#: заголовок можно не прислать, и запреты разд. 63.2 обошлись бы молча.
DELEGATED_CLIENT_CLAIM = "delegated_for"
DELEGATED_FROM_CLAIM = "delegated_from"

#: Хвост адреса делегированной личности. ``.invalid`` — зарезервированный
#: RFC 2606 домен: он никогда не будет делегирован и никому не принадлежит.
DELEGATED_EMAIL_DOMAIN_SUFFIX = ".delegated.invalid"

#: Метка вместо хэша пароля. Ни argon2, ни bcrypt такого не выдают (их вывод
#: начинается с «$»), поэтому спутать её с настоящим хэшем невозможно.
DELEGATED_PASSWORD_MARK = "!delegated-no-password"

#: Роли, которые имеют смысл в чужом контуре: это работа, а не управление.
DELEGATABLE_ROLES = frozenset(
    {
        RoleEnum.OT_PB_LEAD,
        RoleEnum.OT_SPECIALIST,
        RoleEnum.OT_HEAD,
        RoleEnum.PB_ENGINEER,
        RoleEnum.ECOLOGIST,
    }
)

#: Во что опускается всё остальное — включая ``owner`` и ``admin``.
DEFAULT_DELEGATED_ROLE = RoleEnum.OT_SPECIALIST

_SLUG_SAFE = re.compile(r"[^a-z0-9-]+")


def delegated_email(*, specialist_user_id: str, outsourcer_slug: str) -> str:
    """Адрес личности в контуре клиента — вычисляемый и несуществующий.

    Вычисляемый, потому что иначе связь «специалист ↔ его личность в контуре»
    пришлось бы хранить отдельной таблицей, а любая такая таблица однажды
    разойдётся с тем, что на самом деле лежит в контуре клиента.
    """

    user_part = _SLUG_SAFE.sub("-", str(specialist_user_id).strip().lower()).strip("-")
    slug_part = _SLUG_SAFE.sub("-", str(outsourcer_slug).strip().lower()).strip("-")
    if not user_part or not slug_part:
        raise ValueError(
            "Личность делегируется только от известного специалиста известного аутсорсера"
        )
    return f"{user_part}@{slug_part}{DELEGATED_EMAIL_DOMAIN_SUFFIX}"


def is_delegated_email(email: str | None) -> bool:
    """Делегированная ли это личность. Проверка по адресу, а не по флагу.

    Флаг в отдельной колонке пришлось бы проставлять — и он не проставился бы
    ровно там, где личность завели в обход правил.
    """

    return str(email or "").strip().lower().endswith(DELEGATED_EMAIL_DOMAIN_SUFFIX)


def is_delegated_password(hashed: str | None) -> bool:
    """Стоит ли в поле пароля метка «входа по паролю нет»."""

    return str(hashed or "") == DELEGATED_PASSWORD_MARK


def delegated_role(specialist_role: RoleEnum | str | None) -> RoleEnum:
    """Роль личности в контуре клиента.

    Профессиональная роль зеркалится; административная (в том числе владелец)
    НЕ делегируется никогда — иначе ведение охраны труда по договору давало бы
    заодно власть над контуром клиента.
    """

    if isinstance(specialist_role, RoleEnum):
        candidate: RoleEnum | None = specialist_role
    else:
        try:
            candidate = RoleEnum(str(specialist_role or "").strip().lower())
        except ValueError:
            candidate = None
    if candidate in DELEGATABLE_ROLES:
        return candidate
    return DEFAULT_DELEGATED_ROLE


def delegated_display_name(*, specialist_name: str, outsourcer_name: str) -> str:
    """Имя, по которому клиент понимает, кто это.

    Служебная учётка без объяснения в списке пользователей своего контура
    читается как взлом, а не как «наш подрядчик по охране труда».
    """

    who = str(specialist_name or "").strip() or "специалист"
    whose = str(outsourcer_name or "").strip() or "аутсорсера"
    return f"{who} (аутсорсер «{whose}»)"
