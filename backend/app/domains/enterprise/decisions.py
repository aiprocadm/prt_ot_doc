_BY_KEY = {item.key: item for item in ENTERPRISE_DECISIONS}


def decision_for(key: str) -> EnterpriseDecision | None:
    """Решение по ключу. ``None`` — такого требования в реестре нет."""

    return _BY_KEY.get(str(key or "").strip().lower())
