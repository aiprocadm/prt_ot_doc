"""BIZ-53 разд. 53.3: решения по enterprise-аренде — реестр рядом с кодом.

ЗАЧЕМ ЭТОТ ФАЙЛ СУЩЕСТВУЕТ. Разд. 53.3 перечисляет, что нужно крупному
заказчику: индивидуальный онбординг, изоляция уровня «своя база / частное
облако / у себя», SSO/SAML/LDAP, глубокие интеграции (1С, HR, BI/DWH),
выделенный SLA, договор на обработку ПДн, иерархия группы компаний. Часть из
этого сделана, часть сделана НАМЕРЕННО ИНАЧЕ, а часть вообще не делается кодом.

Пока такие решения живут только в отчётах и обсуждениях, происходит одно из
двух: их забывают и делают заново, либо продавец обещает заказчику то, чего
нет. Поэтому решения лежат ЗДЕСЬ, рядом с кодом, и не молчат: отказ настройки
единого входа на ``saml`` и ``ldap`` печатает причину и обходной путь прямо
отсюда. Реестр не украшение — он РАБОТАЕТ.

ТРИ СОСТОЯНИЯ, И НИ ОДНОГО ЧЕТВЁРТОГО.

* ``DONE`` — сделано, и указано, ГДЕ смотреть.
* ``BY_DEPLOYMENT`` — делается развёртыванием, а не кодом приложения.
* ``DECLINED`` — решено не делать, названа причина И ЧТО ДЕЛАТЬ ВМЕСТО.

«Не решено» состояния нет намеренно. Строка без решения — это и есть то, что
потом всплывает на переговорах как «ну, мы думали, это есть».

ПОЧЕМУ У ``DECLINED`` ОБЯЗАТЕЛЕН ОБХОДНОЙ ПУТЬ. «Не поддерживаем» без
продолжения означает для заказчика «идите к конкуренту». Почти всегда нужное
достигается тем, что у платформы уже есть, — и сказать это обязана сама
платформа, а не менеджер по памяти.
"""

