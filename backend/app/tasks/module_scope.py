"""Чей это фоновый обход: модуля или ядра (SEC-63 разд. 63.3, срез-205).

ЧТО НАШЛА СВЕРКА. Разд. 63.3 называет три вида «осиротевших доступов» после
отключения модуля: **API-ключи, вебхуки и ЗАДАЧИ**. Вебхуки гасятся с BIZ-61
(``services/tenants/subscription.py::_prune_module_webhooks``), ручки закрыты
роутовыми гейтами, а фоновые обходы — нет: они берут ВСЕХ активных арендаторов
и работают, не спрашивая, продан ли модуль.

Цена этого видна на живом примере. ``contractors.readiness.tick`` каждую ночь
шлёт уведомления о готовности подрядчиков и пересобирает витрину — арендатору,
у которого модуль «Подрядчики» отключён. Человек получает письмо про раздел,
которого он не видит и за который не платит; в базе продолжают появляться
строки; а если модуль отключили из-за неоплаты или по требованию безопасности,
платформа продолжает обрабатывать те самые данные, обработку которых прекратили.

ПОЧЕМУ РЕЕСТР, А НЕ ПРОВЕРКА ПО ИМЕНИ. Имя задачи похоже на код модуля не
всегда и не обязано: ``ppe.expiry.tick`` выглядит как модуль «СИЗ», но базовые
СИЗ — ЯДРО (модуля ``ppe`` в каталоге нет, есть ``warehouse`` — «Склад СИЗ»,
другое). Угадывание по имени однажды выключило бы ядровой обход у всех.

ПОЭТОМУ У КАЖДОЙ ЗАДАЧИ РАСПИСАНИЯ ДОЛЖНА БЫТЬ ЗАПИСЬ: либо модуль, либо
явное «это ядро» С ПРИЧИНОЙ. Третьего состояния нет, и это стережёт
``tests/test_task_module_scope.py``: новая задача не проскочит мимо решения.
"""

from __future__ import annotations

__all__ = ["CORE_TASKS", "TASK_MODULE", "module_for_task"]

#: Обход принадлежит ПРОДАВАЕМОМУ модулю: у арендатора без него обход
