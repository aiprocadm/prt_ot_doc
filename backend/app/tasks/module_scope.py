def module_for_task(task_name: str) -> str | None:
    """Код модуля обхода или ``None``, если обход ядровой.

    Незарегистрированная задача — ГРОМКАЯ ошибка, а не «наверное, ядро»:
    молчаливое умолчание здесь означает, что новый модульный обход будет
    работать у тех, кто модуль не покупал, и узнают об этом по жалобе.
    """

    if task_name in TASK_MODULE:
        return TASK_MODULE[task_name]
    if task_name in CORE_TASKS:
        return None
    raise KeyError(
        f"задача {task_name!r} не описана в app/tasks/module_scope.py: "
        "укажите её модуль в TASK_MODULE или объявите ядровой в CORE_TASKS с причиной"
    )
