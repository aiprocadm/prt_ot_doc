"""«Высокий риск» — одна формула на продукт (BIZ-54-57 срез-131).

В базе ДВЕ таблицы про риски. Живая — оценки рисков (``risk_assessments`` и
строки ``risk_assessment_items``): их заводит контур рисков, ими считается KPI
отчётов. Мёртвая — реестр ``risk``: в неё не пишет НИКТО во всём
``backend/app``, но по ней до среза-131 считали разрез аналитики, набор строк
конструктора отчётов и ручка ``GET /risk/risks``. Все три показывали ноль
всегда — и это не выглядело поломкой, потому что «ноль рисков» читается как
«рисков нет».

Тот же класс, что «давление происшествий» в срезе-74: экран считал строки
таблицы, которую ни одна ручка не заполняет.

Здесь живёт условие «высокий риск», чтобы разрез аналитики и KPI отчётов
давали ОДНО число: раньше KPI писал ``level.in_([...])`` руками, а разрез
сравнивал числовой уровень мёртвой таблицы с порогом — сойтись они не могли
даже теоретически.
"""

from __future__ import annotations

from sqlalchemy import ColumnElement

from app.models.risk import RiskAssessmentItem

__all__ = ["HIGH_RISK_LEVELS", "high_risk_item_where"]

#: Уровни, которые считаются высокими. Словарь уровней задаёт методология
#: (``modules/risk/calc.py``); здесь — только те, что попадают в счёт.
HIGH_RISK_LEVELS: tuple[str, ...] = ("high", "crit")


def high_risk_item_where(tenant_id: str) -> tuple[ColumnElement[bool], ...]:
    """Условия «строка оценки с высоким уровнем риска» у арендатора.

    Счёт идёт по СТРОКАМ оценки, а не по оценкам целиком: одна оценка
    описывает много опасностей, и «две высокие опасности на одном рабочем
    месте» — это два повода вмешаться, а не один.
    """

    return (
        RiskAssessmentItem.tenant_id == tenant_id,
        RiskAssessmentItem.level.in_(HIGH_RISK_LEVELS),
    )
