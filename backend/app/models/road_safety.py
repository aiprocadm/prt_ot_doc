class Driver(TenantBaseModel, SoftDeleteMixin):
    """Карточка допуска к управлению: удостоверение, категории, стаж.

    ЧЕЛОВЕК НЕ ДУБЛИРУЕТСЯ. ФИО, табельный номер, должность и подразделение
    остаются у ядрового ``Person`` — здесь только водительское. Один человек —
    одна карточка водителя (уникальность в БД): вторая запись о том же
    человеке начинает расхождение, а не заводит второго водителя.

    СТАЖ НЕ ХРАНИТСЯ ЧИСЛОМ. Хранится дата, с которой он идёт, а число лет
    СЧИТАЕТСЯ ПРИ ЧТЕНИИ — как просрочки в остальном продукте. Записанное
    «стаж 3 года» через два года молча превращается в ложь, и отличить её от
    правды нельзя: у числа нет даты, на которую оно верно.

    ГРАНИЦА: платформа НЕ решает, какая категория нужна для конкретной машины
    и достаточен ли стаж для перевозки пассажиров. Это следует из массы,
    числа мест и вида перевозок по закону — таких данных в системе нет.
    Платформа хранит внесённое и показывает сроки.
    """

    __tablename__ = "road_driver"

    #: человек из ядра; ФИО и должность живут там и здесь не повторяются
    person_id: Mapped[str] = mapped_column(
        ForeignKey("person.id"), nullable=False, index=True
    )
    #: номер водительского удостоверения — уникален у арендатора: один и тот
    #: же номер у двух людей это ошибка ввода, а не два водителя
    license_number: Mapped[str] = mapped_column(String(32), nullable=False)
    #: категории из закрытого словаря; список, потому что в удостоверении их
    #: обычно несколько
    categories: Mapped[list[str]] = mapped_column(
        MutableList.as_mutable(JSON), nullable=False, default=list
    )
    license_issued_at: Mapped[date | None] = mapped_column(Date, nullable=True)
    #: удостоверение действительно до; пусто — СВЕДЕНИЙ НЕТ, а не «бессрочно»:
    #: у водительского удостоверения бессрочности не бывает (как у полиса и
    #: диагностической карты в срезе-1)
    license_due: Mapped[date | None] = mapped_column(Date, nullable=True)
    #: дата, с которой идёт водительский стаж; число лет считается при чтении
    experience_since: Mapped[date | None] = mapped_column(Date, nullable=True)
    status: Mapped[str] = mapped_column(String(16), nullable=False, default="admitted")
    notes: Mapped[str | None] = mapped_column(Text)

    person: Mapped[Person] = relationship(backref="driver_cards")

    __table_args__ = (
        UniqueConstraint("tenant_id", "person_id", name="uq_driver_person"),
        UniqueConstraint("tenant_id", "license_number", name="uq_driver_license"),
        Index("ix_driver_tenant_status", "tenant_id", "status"),
    )


