class Waybill(TenantBaseModel, SoftDeleteMixin):
    """Путевой лист: машина, водитель и отметки контроля перед выездом.

    ПОЧЕМУ ОДНА СУЩНОСТЬ, А НЕ ЧЕТЫРЕ. ТЗ перечисляет «предрейсовые и
    послерейсовые медосмотры, предрейсовый техконтроль, путевые листы,
    журналы» — но это не четыре реестра, а один документ и три отметки на нём.
    Заведи их отдельными списками — и придётся сшивать записи об одном рейсе
    по времени и фамилии, а первое же расхождение сделает вопрос «выпускали ли
    машину законно» неотвечаемым.

    ЖУРНАЛ ОТДЕЛЬНО НЕ ЗАВОДИТСЯ. Журнал предрейсовых медосмотров — это тот же
    список листов за период, а не второе хранилище тех же фактов. Реестр с
    отбором по датам И ЕСТЬ журнал; параллельный список разошёлся бы с листами.

    ЯДРО НЕ ДУБЛИРУЕТСЯ. Предрейсовый осмотр — НЕ ядровой ``MedicalExam``: тот
    про профмедосмотры (периодический, предварительный, психиатрический) —
    раз в год, по вредным факторам, с заключением. Предрейсовый — каждую
    смену, за две минуты, привязан к рейсу. Общее у них только слово
    «медосмотр».

    ГРАНИЦА: платформа НЕ решает, законен ли выпуск. Она показывает, что
    ВНЕСЕНО: отметки поставлены, не поставлены или не пройдены. Обязателен ли
    послерейсовый осмотр, уложился ли водитель в режим труда и отдыха и
    достаточно ли этих отметок по закону — следует из вида перевозок и
    суммирования за неделю, чего в системе нет.
    """

    __tablename__ = "road_waybill"

    #: номер листа — уникален у арендатора: два листа с одним номером это
    #: ошибка ввода, а не два рейса (как госномер в срезе-1)
    number: Mapped[str] = mapped_column(String(32), nullable=False)
    #: машина и водитель — из реестров БДД, а не строками: строка «Иванов» не
    #: свяжется с карточкой допуска, и вопрос «выпускали ли отстранённого»
    #: остался бы без ответа
    vehicle_id: Mapped[str] = mapped_column(
        ForeignKey("road_vehicle.id"), nullable=False, index=True
    )
    driver_id: Mapped[str] = mapped_column(
        ForeignKey("road_driver.id"), nullable=False, index=True
    )
    #: дата выдачи — по ней лист попадает в журнал за период
    issued_on: Mapped[date] = mapped_column(Date, nullable=False)
    #: выезд и возвращение; пусто — сведений нет. Время в рейсе СЧИТАЕТСЯ ПРИ
    #: ЧТЕНИИ из этой пары и числом не хранится
    departure_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True), nullable=True
    )
    return_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True), nullable=True
    )
    #: три отметки контроля; по умолчанию «сведения не внесены» — свежий лист
    #: не считается ни пройденным, ни проваленным
    pre_trip_medical: Mapped[str] = mapped_column(
        String(16), nullable=False, default="not_recorded"
    )
    post_trip_medical: Mapped[str] = mapped_column(
        String(16), nullable=False, default="not_recorded"
    )
    pre_trip_technical: Mapped[str] = mapped_column(
        String(16), nullable=False, default="not_recorded"
    )
    status: Mapped[str] = mapped_column(String(16), nullable=False, default="issued")
    notes: Mapped[str | None] = mapped_column(Text)

    vehicle: Mapped[Vehicle] = relationship(backref="waybills")
    driver: Mapped[Driver] = relationship(backref="waybills")

    __table_args__ = (
        UniqueConstraint("tenant_id", "number", name="uq_waybill_number"),
        Index("ix_waybill_tenant_issued", "tenant_id", "issued_on"),
    )
