"""БДД — предметные модели дисциплины (Доп. №1 разд. 56.2).

Архитектурный принцип мультидисциплинарности (преамбула разд. 54): общее ядро
(люди, площадки, документы, задачи, календарь) НЕ дублируется — дисциплина
добавляет только своё. Первая собственная сущность контура БДД — реестр
транспортных средств.

ПОЧЕМУ СВОЯ СУЩНОСТЬ. До этого среза по разд. 56.2 не было НИ ОДНОЙ модели
транспорта: ТЗ отсылает к «transport safety (vNext §17.3)», но в коде есть
только словарная строка дисциплины, комплект документов BDD_BASE и запись в
библиотеке правил. Ни ТС, ни водителей, ни путевых листов.

Срез-2 добавляет ВОДИТЕЛЕЙ. Человека платформа уже знает (ядровой ``Person``),
поэтому карточка водителя его НЕ ДУБЛИРУЕТ: она ссылается на человека и
добавляет только своё — водительское удостоверение, категории, стаж и допуск к
управлению. Дублировать ФИО значило бы завести второй список сотрудников,
который тут же разойдётся с первым.

Срез-3 добавляет ПУТЕВЫЕ ЛИСТЫ. Лист — это место, где сходятся машина,
водитель и три отметки контроля (предрейсовый медосмотр, послерейсовый
медосмотр, предрейсовый техконтроль): в жизни их ставят именно на листе, и
разносить их по трём параллельным реестрам значило бы получить три списка,
которые разойдутся.

Учёт ДТП и нарушения — следующие срезы.
"""

