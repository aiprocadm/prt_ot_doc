"""Ответственный арендатора за нормативный акт (B.18 разд. 19.1 «owner», срез-203).

ЗАЧЕМ. Разд. 19.1 перечисляет, что обязан поддерживать реестр НПА: федеральные
акты, локальные акты, редакции, даты вступления и отмены, ссылки на процессы и
сущности, **owner**, статус актуальности. Всё, кроме owner, закрыто срезами
141–202.

ПОЧЕМУ «owner» — ЭТО ОТВЕТСТВЕННЫЙ, А НЕ «ЧЕЙ АКТ». Прошлая волна записала
остаток строки как «federal/local и owner» одной фразой, то есть читала owner
как принадлежность акта. Это прочтение не выдерживает проверки: «федеральные
НПА» и «локальные НПА» — уже два отдельных пункта того же списка, и третий
пункт про то же самое был бы повтором. Рядом, в разд. 19.2, тот же документ
пишет «responsible owner» про требование — человека. Значит, и здесь owner —
человек: кто в организации ведёт этот акт.

ПОЧЕМУ ОТДЕЛЬНАЯ АРЕНДАТОРСКАЯ ТАБЛИЦА, А НЕ КОЛОНКА У ``npa_act``. Один и тот
же приказ Минтруда действует на всех арендаторов, и ведут его в каждой
организации РАЗНЫЕ люди. Колонка у общей строки дала бы одного ответственного на
всю платформу — то есть ответ, который верен максимум для одного арендатора.

ЧТО ЭТО МЕНЯЕТ НА ДЕЛЕ. Задачи актуализации (разд. 19.4) раньше доставались
тому, кто нажал кнопку. Теперь — постоянному ответственному, если он назначен:
«пересмотреть документы после новой редакции» должно попадать к тому, кто за
акт отвечает, а не к тому, кто первым открыл экран.
"""

from __future__ import annotations

from sqlalchemy import ForeignKey, String, UniqueConstraint
from sqlalchemy.orm import Mapped, mapped_column

from app.models.base import TenantBaseModel

__all__ = ["NpaActResponsible"]


class NpaActResponsible(TenantBaseModel):
    """Кто в этой организации ведёт этот акт. Одна строка на пару.

    Таблица арендаторская, поэтому армируется RLS (SEC-65): в ней связка
    «человек ↔ акт», и чужая такая связка рассказывает, чем занимается чужая
    организация.
    """

    __tablename__ = "npa_act_responsible"

    #: Акт общего реестра. Простой столбец без ``ForeignKey`` в ORM — ключ из
    #: tenant-базы в shared-базу ломает ``create_all`` (прецедент
    #: ``NPABinding.npa_id`` и ``ComplianceRequirement.npa_id``); настоящий ключ
    #: ставит PostgreSQL миграцией.
    npa_id: Mapped[str] = mapped_column(String(36), nullable=False, index=True)

    #: Ответственный. ``SET NULL`` при удалении человека, а не удаление строки:
    #: «акт ведём, ответственный уволился» и «акт никто не ведёт» — разные
    #: состояния, и первое обязано быть видно.
    owner_user_id: Mapped[str | None] = mapped_column(
        String(36), ForeignKey("user.id", ondelete="SET NULL"), nullable=True, index=True
    )

    __table_args__ = (UniqueConstraint("tenant_id", "npa_id", name="uq_npa_act_responsible"),)
