"""SEC-64, разд. 64.1, строка «Injection»: что вообще можно вклеивать в текст SQL.

ЗАЧЕМ ЭТОТ ДОМ. Таблица OWASP Top-10 из Доп.№3 требует по строке «Injection»
параметризованных запросов. Разбор ПО КОДУ (AST, не по тексту) нашёл в
приложении четырнадцать мест, где SQL всё-таки собирается из кусков, и они
делятся на ДВА РАЗНЫХ СЛУЧАЯ, которые нельзя путать:

1. **Имя объекта базы** (схема, таблица, колонка). Параметром его передать
   нельзя — драйвер подставляет значения, а не идентификаторы. Значит, склейка
   неизбежна, и единственная защита — жёсткая проверка формата плюс правило
   «имя берётся из нашего же реестра, а не из запроса».
2. **Значение** (метка сессии, любые данные). Здесь склейка не нужна НИКОГДА:
   у драйвера есть параметры. Склеивать значение — ошибка независимо от того,
   насколько тщательно его «обезвредили».

НАЙДЕННЫЙ ДЕФЕКТ (срез-210), из-за которого дом и появился. Метка сессии
собиралась так::

    safe = ctx.correlation_id.replace('"', "")
    text(f"SET LOCAL application_name TO 'api:{safe}'")

``correlation_id`` — это значение заголовка запроса (``X-Correlation-Id`` и два
его синонима): снаружи, без проверки символов, только обрезка до 128 знаков.
А «обезвреживание» снимало ДВОЙНУЮ кавычку, хотя строка стоит в ОДИНАРНЫХ —
то есть убирало не тот знак. Проверка на живом PostgreSQL 16: заголовок
``X-Correlation-Id: x'`` превращал запрос в ``'api:x''`` и ронял настройку
сессии с синтаксической ошибкой.

ЧЕСТНО О ГРАНИЦЕ. Дописать ВТОРОЙ запрос («; INSERT ...») через этот путь не
удалось: SQLAlchemy поверх asyncpg шлёт запрос подготовленным, а такой протокол
запрещает два запроса сразу — проверено, попытка падает. То есть дыра держалась
НА МИЛОСТИ ДРАЙВЕРА, а не на нашей защите: смена драйвера или переход на простой
протокол открыли бы её целиком. Поэтому чиним не «добавим ещё один replace», а
так, чтобы значение из запроса ПЕРЕСТАЛО БЫТЬ ТЕКСТОМ SQL.

КАК ЧИНИТСЯ. ``SET`` не принимает параметров, но у PostgreSQL есть функция
``set_config(имя, значение, только_в_транзакции)`` — обычный вызов, куда
значение уходит НАСТОЯЩИМ ПАРАМЕТРОМ. Проверено вживую: кавычка, точка с
запятой и попытка дописать запрос сохраняются как ОБЫЧНЫЙ ТЕКСТ метки.
"""

from __future__ import annotations

import re
from typing import Final

from sqlalchemy import TextClause, text

__all__ = [
    "MAX_IDENTIFIER_LENGTH",
    "SESSION_LABEL_PREFIX",
    "UnsafeSqlIdentifier",
    "assert_safe_identifier",
    "quote_identifier",
    "session_label_params",
    "session_label_statement",
]

#: PostgreSQL обрезает имена длиннее 63 байт — более длинное имя всё равно не
#: то, которое имели в виду.
MAX_IDENTIFIER_LENGTH: Final[int] = 63

#: Разрешены буквы латиницы, цифры, подчёркивание и дефис; первым знаком — не
#: цифра. Намеренно УЖЕ, чем позволяет PostgreSQL в кавычках: все имена в этом
#: продукте такие, а «на всякий случай пошире» — это и есть щель.
#:
#: ДЕФИС РАЗРЕШЁН НЕ ИЗ ДОБРОТЫ. Слаг арендатора описан как ``[a-z][a-z0-9_-]``,
#: а схема зовётся ``tenant_<слаг>`` — то есть ``tenant_demo-corp`` это НАСТОЯЩЕЕ
#: имя живого арендатора. Запрет дефиса сломал бы таких арендаторов целиком.
#: Опасны не дефис, а кавычка, пробел и точка с запятой — их здесь нет, и имя всё
#: равно уходит в кавычках.
_SAFE_IDENTIFIER: Final[re.Pattern[str]] = re.compile(r"^[A-Za-z_][A-Za-z0-9_-]*$")

#: Приставка метки сессии: по ней в ``pg_stat_activity`` видно, что соединение
#: пришло из API, а не от фоновой задачи или человека с консолью.
SESSION_LABEL_PREFIX: Final[str] = "api:"


class UnsafeSqlIdentifier(ValueError):
    """Имя объекта базы не прошло проверку формата.

    Это НЕ пользовательская ошибка, а признак того, что в склейку SQL попало
    имя из недоверенного источника. Поэтому исключение шумное и с указанием
    источника: молча отбросить такое имя значило бы спрятать дыру.
    """

    def __init__(self, name: str, source: str) -> None:
        super().__init__(f"небезопасное имя объекта базы {name!r} (источник: {source})")
        self.name = name
        self.source = source


def assert_safe_identifier(name: str, *, source: str) -> str:
    """Проверить имя объекта базы перед склейкой в SQL.

    Args:
        name: имя схемы, таблицы или колонки.
        source: откуда имя взято — попадает в текст ошибки, чтобы при падении
            сразу было видно, какой реестр подсунул негодное имя.

    Raises:
        UnsafeSqlIdentifier: имя пустое, слишком длинное или содержит что-то
            кроме букв латиницы, цифр и подчёркивания.
    """

    if not name or len(name) > MAX_IDENTIFIER_LENGTH or not _SAFE_IDENTIFIER.fullmatch(name):
        raise UnsafeSqlIdentifier(name, source)
    return name


def quote_identifier(name: str, *, source: str) -> str:
    """Проверенное имя в двойных кавычках — готовый кусок SQL.

    Кавычки нужны и после проверки: без них имя, совпавшее со словом языка
    запросов, сломает запрос. Проверка и кавычки ходят парой, поэтому живут в
    одной функции — разделить их значит однажды забыть половину.
    """

    return f'"{assert_safe_identifier(name, source=source)}"'


def session_label_statement() -> TextClause:
    """Запрос, помечающий соединение — БЕЗ склейки.

    ``SET`` параметров не принимает, ``set_config`` — принимает. Значение
    уходит параметром и текстом запроса не становится.
    """

    return text("SELECT set_config('application_name', :value, true)")


def session_label_params(correlation_id: str) -> dict[str, str]:
    """Значение метки для :func:`session_label_statement`.

    Ничего не «обезвреживаем»: чинить кавычки в значении — работа драйвера, а
    наше дело — не превращать значение в текст запроса.
    """

    return {"value": f"{SESSION_LABEL_PREFIX}{correlation_id}"}
