"""Дисциплины охраны труда и смежных областей (Доп. №1 разд. 54–57).

ТЗ называет шесть дисциплин (ОТ / ПБ / ПромБез / Экология / ГО-ЧС / БДД), и
разд. 57.2 требует единый «Центр внимания» ПО ВСЕМ ним. Здесь лежит общий
словарь дисциплин — единственный на весь продукт.

**Почему словарь переехал сюда.** Он появился в светофоре клиента
(``domains/managed_clients/readiness.py``, BIZ-51 срез-5) и там же жил. Второй
такой словарь рядом с Центром внимания разошёлся бы с первым на первой же
правке, и «Медосмотры» на двух соседних экранах стали бы означать разное.
Поэтому определения переехали в ядро, а светофор берёт их отсюда: направление
зависимости domains → core обычное, обратное было бы новым для проекта.

## Три вида ответа про источник данных

Модуль отвечает на вопрос «запись такого-то вида — это какая дисциплина?», и
третий ответ так же важен, как первые два:

1. **Сопоставлено** — дисциплина следует из самой таблицы (медосмотр →
   «Медосмотры»).
2. **Не классифицировано** — источник дисциплину НЕ хранит. Наряд-допуск,
   проверка, срок соответствия и свободное событие календаря бывают любой
   дисциплины, и разметить их «по смыслу названия» значило бы выдумать данные,
   которых в базе нет. Каждый такой источник назван вместе с причиной, а не
   спрятан молчанием.
3. **Не измеряется** — дисциплина в ТЗ есть, а данных о ней нет вовсе.
   Показать по ней ноль (тем более зелёный) означало бы сказать «нарушений
   нет» вместо «мы это не считаем» — то же правило, что у светофора BIZ-51 и
   у расхода BIZ-52.

``ALL_SOURCES`` из ``app.services.calendar_aggregator`` здесь намеренно НЕ
импортируется: это утащило бы в ядро модели и SQLAlchemy. Полноту покрытия —
каждый источник агрегатора либо размечен, либо назван неклассифицированным —
стережёт тест ``backend/tests/test_attention_disciplines.py``.
"""

from __future__ import annotations

import enum

__all__ = [
    "ATTENTION_SOURCES",
    "PERMIT_WORK_TYPE_DISCIPLINE",
    "UNMAPPED_PERMIT_WORK_TYPES",
    "discipline_of_permit",
    "DISCIPLINE_TITLES",
    "MEASURED_DISCIPLINES",
    "PERSON_SCOPED_SOURCES",
    "SOURCE_DISCIPLINE",
    "UNCLASSIFIED_SOURCES",
    "UNMEASURED_DISCIPLINES",
    "Discipline",
    "discipline_of",
]


class Discipline(str, enum.Enum):
    """Дисциплины ТЗ: измеримые сегодня + названные в разд. 54–56."""

    MEDICAL = "medical"
    PPE = "ppe"
    TRAINING = "training"
    FIRE_SAFETY = "fire_safety"
    INDUSTRIAL_SAFETY = "industrial_safety"
    ECOLOGY = "ecology"
    CIVIL_DEFENSE = "civil_defense"
    ROAD_SAFETY = "road_safety"


DISCIPLINE_TITLES: dict[Discipline, str] = {
    Discipline.MEDICAL: "Медосмотры",
    Discipline.PPE: "СИЗ",
    Discipline.TRAINING: "Обучение",
    Discipline.FIRE_SAFETY: "Пожарная безопасность",
    Discipline.INDUSTRIAL_SAFETY: "Промышленная безопасность",
    Discipline.ECOLOGY: "Экология",
    Discipline.CIVIL_DEFENSE: "ГО и ЧС",
    Discipline.ROAD_SAFETY: "БДД",
}

#: Дисциплины, по которым в системе есть поимённые данные.
MEASURED_DISCIPLINES: tuple[Discipline, ...] = (
    Discipline.MEDICAL,
    Discipline.PPE,
    Discipline.TRAINING,
)

#: Дисциплины без поимённого учёта — отдаются с причиной, не с цветом и не нулём.
UNMEASURED_DISCIPLINES: dict[Discipline, str] = {
    Discipline.FIRE_SAFETY: "Поимённый учёт пожарной безопасности в системе не ведётся",
    Discipline.INDUSTRIAL_SAFETY: "Поимённый учёт промышленной безопасности в системе не ведётся",
    Discipline.ECOLOGY: "Поимённый учёт экологии в системе не ведётся",
    Discipline.CIVIL_DEFENSE: "Поимённый учёт ГО и ЧС в системе не ведётся",
    Discipline.ROAD_SAFETY: "Поимённый учёт БДД в системе не ведётся",
}

#: Источник календаря → дисциплина. Ключи — коды из
#: ``CalendarAggregatorService.ALL_SOURCES``. Размечены ТОЛЬКО те источники, у
#: которых дисциплина следует из таблицы, а не из догадки о названии.
SOURCE_DISCIPLINE: dict[str, Discipline] = {
    "medical_exam": Discipline.MEDICAL,
    "medical_referral": Discipline.MEDICAL,
    "ppe_issue": Discipline.PPE,
    "training_session": Discipline.TRAINING,
    # Инструктажи — часть обучения по охране труда: виды в системе закрытые
    # (вводный, первичный, повторный, целевой, внеплановый), «пожарного» вида
    # среди них нет. Появится — разметку пересмотреть.
    "briefing_entry": Discipline.TRAINING,
}

#: Источники БЕЗ дисциплины — каждый с причиной. Причина уходит в ответ API:
#: «источника нет в списке» и «источник намеренно не размечен» — разные вещи,
#: и молчание про второе однажды прочитают как первое.
UNCLASSIFIED_SOURCES: dict[str, str] = {
    "permit": (
        "Наряд-допуск: дисциплина следует только у части видов работ "
        "(огневые, газоопасные), у остальных это общая охрана труда — "
        "источник целиком к одной дисциплине не относится"
    ),
    "inspection": (
        "Проверка: в записи есть надзорный орган, но не дисциплина; "
        "поимённого учёта у проверок нет вовсе"
    ),
    "compliance_deadline": (
        "Срок соответствия: привязан к произвольной сущности, "
        "дисциплина не хранится"
    ),
    "calendar_event": (
        "Свободное событие календаря: вид задаёт пользователь, "
        "ни дисциплины, ни человека в записи нет"
    ),
}

#: Источники, которые агрегатор умеет сузить до конкретного человека. Список
#: ЯВНЫЙ, потому что у остальных фильтр по человеку молча не применяется — а
#: молча выданная чужая запись это утечка персональных данных, а не косметика.
PERSON_SCOPED_SOURCES: frozenset[str] = frozenset(
    {
        "medical_exam",
        "medical_referral",
        "ppe_issue",
        "training_session",
        "briefing_entry",
    }
)

#: Что Центр внимания спрашивает у агрегатора. Неразмеченные источники не
#: запрашиваются вовсе: их строки всё равно не к чему отнести, а каждый лишний
#: источник — это лишние запросы на посадочной странице.
ATTENTION_SOURCES: tuple[str, ...] = tuple(SOURCE_DISCIPLINE)


def discipline_of(source_type: str) -> Discipline | None:
    """Дисциплина источника или ``None`` — «не классифицировано»."""

    return SOURCE_DISCIPLINE.get(source_type)


#: Вид работ наряда-допуска → дисциплина. Размечены ТОЛЬКО те виды, у которых
#: дисциплина следует из закона, а не из ощущения:
#:
#: * ``hot_work`` — огневые работы: наряд-допуск на них требуют Правила
#:   противопожарного режима, это пожарная безопасность;
#: * ``gas_hazardous`` — газоопасные работы: их ведение регулируют ФНП
#:   Ростехнадзора, это промышленная безопасность.
#:
#: Остальные четыре вида (высота, замкнутые пространства, земляные,
#: электроустановки) — общая охрана труда. Отдельной дисциплины «Охрана труда»
#: в словаре НЕТ: она разложена на медосмотры / СИЗ / обучение, а наряд-допуск
#: ни к одному из трёх не относится. Приписать его к любому из них значило бы
#: подменить дисциплину ради заполненной клетки.
PERMIT_WORK_TYPE_DISCIPLINE: dict[str, Discipline] = {
    "hot_work": Discipline.FIRE_SAFETY,
    "gas_hazardous": Discipline.INDUSTRIAL_SAFETY,
}

#: Виды работ без дисциплины — с общей причиной, а не молчанием.
UNMAPPED_PERMIT_WORK_TYPES: str = (
    "общая охрана труда: отдельной дисциплины для неё в словаре нет"
)


def discipline_of_permit(work_type: str) -> Discipline | None:
    """Дисциплина вида работ наряда-допуска или ``None`` — «общая охрана труда»."""

    return PERMIT_WORK_TYPE_DISCIPLINE.get(work_type)
