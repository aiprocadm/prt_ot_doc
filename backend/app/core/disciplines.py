"""Дисциплины охраны труда и смежных областей (Доп. №1 разд. 54–57).

ТЗ называет шесть дисциплин (ОТ / ПБ / ПромБез / Экология / ГО-ЧС / БДД), и
разд. 57.2 требует единый «Центр внимания» ПО ВСЕМ ним. Здесь лежит общий
словарь дисциплин — единственный на весь продукт.

**Почему словарь переехал сюда.** Он появился в светофоре клиента
(``domains/managed_clients/readiness.py``, BIZ-51 срез-5) и там же жил. Второй
такой словарь рядом с Центром внимания разошёлся бы с первым на первой же
правке, и «Медосмотры» на двух соседних экранах стали бы означать разное.
Поэтому определения переехали в ядро, а светофор берёт их отсюда: направление
зависимости domains → core обычное, обратное было бы новым для проекта.

## Три вида ответа про источник данных

Модуль отвечает на вопрос «запись такого-то вида — это какая дисциплина?», и
третий ответ так же важен, как первые два:

1. **Сопоставлено** — дисциплина следует из самой таблицы (медосмотр →
   «Медосмотры»).
2. **Не классифицировано** — источник дисциплину НЕ хранит. Наряд-допуск,
   проверка, срок соответствия и свободное событие календаря бывают любой
   дисциплины, и разметить их «по смыслу названия» значило бы выдумать данные,
   которых в базе нет. Каждый такой источник назван вместе с причиной, а не
   спрятан молчанием.
3. **Не измеряется** — дисциплина в ТЗ есть, а данных о ней нет вовсе.
   Показать по ней ноль (тем более зелёный) означало бы сказать «нарушений
   нет» вместо «мы это не считаем» — то же правило, что у светофора BIZ-51 и
   у расхода BIZ-52.

``ALL_SOURCES`` из ``app.services.calendar_aggregator`` здесь намеренно НЕ
импортируется: это утащило бы в ядро модели и SQLAlchemy. Полноту покрытия —
каждый источник агрегатора либо размечен, либо назван неклассифицированным —
стережёт тест ``backend/tests/test_attention_disciplines.py``.
"""

