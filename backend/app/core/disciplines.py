#: Источники, которые агрегатор умеет сузить до конкретного человека. Список
#: ЯВНЫЙ, потому что у остальных фильтр по человеку молча не применяется — а
#: молча выданная чужая запись это утечка персональных данных, а не косметика.
PERSON_SCOPED_SOURCES: frozenset[str] = frozenset(
    {
        "medical_exam",
        "medical_referral",
        "ppe_issue",
        "training_session",
        "briefing_entry",
    }
)

#: Что Центр внимания спрашивает у агрегатора. Неразмеченные источники не
#: запрашиваются вовсе: их строки всё равно не к чему отнести, а каждый лишний
#: источник — это лишние запросы на посадочной странице.
ATTENTION_SOURCES: tuple[str, ...] = tuple(SOURCE_DISCIPLINE)


def attention_sources(*, person_id: str | None) -> tuple[str, ...]:
    """Источники Центра внимания с учётом того, сужаем ли мы список до человека.

    Разд. 55.3 добавил источники, у которых человека НЕТ ВООБЩЕ: срок действия
    разрешения и плановый замер ПЭК — задача организации, а не сотрудника.
    Раньше правило было «спрашиваем всё размеченное», и оно молча
    предполагало, что каждый размеченный источник умеет сузиться до человека.

    Поэтому: когда список сужается до человека (рабочая роль), спрашиваем
    ТОЛЬКО те источники, которые это умеют — иначе агрегатор молча вернул бы
    чужие записи. Когда сужения нет (роли, которым записи арендатора и так
    открыты), спрашиваем всё размеченное, включая общеорганизационные сроки.
    """

    if person_id is None:
        return ATTENTION_SOURCES
    return tuple(code for code in ATTENTION_SOURCES if code in PERSON_SCOPED_SOURCES)


def discipline_of(source_type: str) -> Discipline | None:
    """Дисциплина источника или ``None`` — «не классифицировано»."""

    return SOURCE_DISCIPLINE.get(source_type)


#: Вид работ наряда-допуска → дисциплина. Размечены ТОЛЬКО те виды, у которых
#: дисциплина следует из закона, а не из ощущения:
#:
#: * ``hot_work`` — огневые работы: наряд-допуск на них требуют Правила
#:   противопожарного режима, это пожарная безопасность;
#: * ``gas_hazardous`` — газоопасные работы: их ведение регулируют ФНП
#:   Ростехнадзора, это промышленная безопасность.
#:
#: Остальные четыре вида (высота, замкнутые пространства, земляные,
#: электроустановки) — общая охрана труда. Отдельной дисциплины «Охрана труда»
#: в словаре НЕТ: она разложена на медосмотры / СИЗ / обучение, а наряд-допуск
